from sqlalchemy import (
    Boolean,
    Column,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    Integer,
    PrimaryKeyConstraint,
    SmallInteger,
    Table,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects.postgresql import ARRAY, JSONB, TIMESTAMP, UUID

from aegis.db.metadata import metadata

tasks = Table(
    "tasks",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("initiator_id", UUID(as_uuid=True), ForeignKey("aegis.identities.id"), nullable=False),
    Column("owner_id", UUID(as_uuid=True), ForeignKey("aegis.identities.id"), nullable=False),
    Column("submitted_credential_id", UUID(as_uuid=True), nullable=False),
    Column("kind", Text, nullable=False),
    Column("input", JSONB, nullable=False),
    Column("state", Text, nullable=False, server_default=text("'created'")),
    Column("version", Integer, nullable=False, server_default=text("0")),
    Column("idempotency_key", Text, nullable=False),
    Column("request_fingerprint", Text, nullable=False),
    Column("cancel_requested_at", TIMESTAMP(timezone=True)),
    Column("cancel_requested_by", UUID(as_uuid=True), ForeignKey("aegis.identities.id")),
    Column("result", JSONB(none_as_null=True)),
    Column("failure_code", Text),
    Column("created_at", TIMESTAMP(timezone=True), nullable=False, server_default=text("now()")),
    Column("updated_at", TIMESTAMP(timezone=True), nullable=False, server_default=text("now()")),
    Column("finished_at", TIMESTAMP(timezone=True)),
    UniqueConstraint("id", "initiator_id", name="uq_tasks_id_initiator_id"),
    UniqueConstraint("id", "owner_id", name="uq_tasks_id_owner_id"),
    UniqueConstraint(
        "initiator_id", "idempotency_key", name="uq_tasks_initiator_id_idempotency_key"
    ),
    ForeignKeyConstraint(
        ["submitted_credential_id", "initiator_id"],
        ["aegis.credentials.id", "aegis.credentials.identity_id"],
        name="fk_tasks_submitted_credential_id_credentials",
    ),
)

security_decisions = Table(
    "security_decisions",
    metadata,
    Column("id", UUID(as_uuid=True), primary_key=True),
    Column("decided_at", TIMESTAMP(timezone=True), nullable=False, server_default=text("now()")),
    Column("actor_id", UUID(as_uuid=True), nullable=False),
    Column("actor_kind", Text, nullable=False),
    Column("actor_credential_id", UUID(as_uuid=True)),
    Column("subject_id", UUID(as_uuid=True), ForeignKey("aegis.identities.id"), nullable=False),
    Column("action", Text, nullable=False),
    Column("resource_type", Text, nullable=False),
    Column("resource_id", Text),
    Column("resource_owner_id", UUID(as_uuid=True)),
    Column("task_id", UUID(as_uuid=True)),
    Column("effect", Text, nullable=False),
    Column("stage", Text, nullable=False),
    Column("reason_codes", ARRAY(Text), nullable=False),
    Column("policy_version", Text, nullable=False),
    Column("policy_digest", Text, nullable=False),
    Column("request_id", Text),
    Column("job_id", UUID(as_uuid=True)),
    Column("job_attempt", Integer),
    Column("inputs", JSONB, nullable=False, server_default=text("'{}'::jsonb")),
    UniqueConstraint(
        "id",
        "task_id",
        "action",
        "effect",
        "stage",
        "decided_at",
        name="uq_security_decisions_transition_key",
    ),
    ForeignKeyConstraint(
        ["actor_id", "actor_kind"],
        ["aegis.identities.id", "aegis.identities.kind"],
        name="fk_security_decisions_actor_id_identities",
    ),
    ForeignKeyConstraint(
        ["actor_credential_id", "actor_id"],
        ["aegis.credentials.id", "aegis.credentials.identity_id"],
        name="fk_security_decisions_actor_credential_id_credentials",
    ),
    ForeignKeyConstraint(
        ["task_id", "subject_id"],
        ["aegis.tasks.id", "aegis.tasks.initiator_id"],
        name="fk_security_decisions_task_id_tasks",
    ),
    ForeignKeyConstraint(
        ["task_id", "resource_owner_id"],
        ["aegis.tasks.id", "aegis.tasks.owner_id"],
        name="fk_security_decisions_task_id_owner_tasks",
    ),
    Index("ix_security_decisions_task_id", "task_id"),
)

task_transition_rules = Table(
    "task_transition_rules",
    metadata,
    Column("id", SmallInteger, primary_key=True, autoincrement=False),
    Column("from_state", Text, nullable=False),
    Column("to_state", Text, nullable=False),
    Column("action", Text),
    Column("effect", Text),
    Column("stage", Text),
    Column("requires_job", Boolean, nullable=False),
    UniqueConstraint(
        "from_state",
        "to_state",
        "action",
        "effect",
        "stage",
        name="uq_task_transition_rules_rule",
        postgresql_nulls_not_distinct=True,
    ),
)

task_state_transitions = Table(
    "task_state_transitions",
    metadata,
    Column("task_id", UUID(as_uuid=True), ForeignKey("aegis.tasks.id"), nullable=False),
    Column("to_version", Integer, nullable=False),
    Column("from_state", Text, nullable=False),
    Column("to_state", Text, nullable=False),
    Column("actor_id", UUID(as_uuid=True), ForeignKey("aegis.identities.id"), nullable=False),
    Column("reason_code", Text, nullable=False),
    Column("decision_id", UUID(as_uuid=True), unique=True),
    Column("decision_action", Text),
    Column("decision_effect", Text),
    Column("decision_stage", Text),
    Column("decision_decided_at", TIMESTAMP(timezone=True)),
    Column("job_id", UUID(as_uuid=True)),
    Column("job_attempt", Integer),
    Column("request_id", Text),
    Column("occurred_at", TIMESTAMP(timezone=True), nullable=False, server_default=text("now()")),
    PrimaryKeyConstraint("task_id", "to_version", name="pk_task_state_transitions"),
    ForeignKeyConstraint(
        [
            "decision_id",
            "task_id",
            "decision_action",
            "decision_effect",
            "decision_stage",
            "decision_decided_at",
        ],
        [
            "aegis.security_decisions.id",
            "aegis.security_decisions.task_id",
            "aegis.security_decisions.action",
            "aegis.security_decisions.effect",
            "aegis.security_decisions.stage",
            "aegis.security_decisions.decided_at",
        ],
        name="fk_task_state_transitions_decision_id_security_decisions",
    ),
)
